// Regenerate src/door.ts and docs/published/FRONTDOOR.md from the source text.
// Run after editing either text: node scripts/embed-door.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const escapeTemplate = value => value
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${')

const frontdoorSource = readFileSync('src/frontdoor.txt', 'utf8')
const referenceSource = readFileSync('src/reference.txt', 'utf8')
const llmsSource = readFileSync('src/llms.txt', 'utf8')
const { renderReferenceSectionIndex, splitReferenceSections } = await import(
  pathToFileURL(resolve('src/reference-sections.ts')).href
)
const frontdoorDocumentPath = 'docs/published/FRONTDOOR.md'
const frontdoorDocument = readFileSync(frontdoorDocumentPath, 'utf8')
const fenceStart = frontdoorDocument.indexOf('```\n')
const fenceEnd = frontdoorDocument.lastIndexOf('\n```')

if (fenceStart < 0 || fenceEnd <= fenceStart) {
  throw new Error(`${frontdoorDocumentPath} canonical fence is missing`)
}

const sources = [frontdoorSource, referenceSource, llmsSource]
const needsFactRendering = sources.some(source => source.includes('{{'))
const cityHelp = needsFactRendering
  ? await import(pathToFileURL(resolve('src/city-help.ts')).href)
  : null
const cityFacts = needsFactRendering
  ? await import(pathToFileURL(resolve('src/city-facts.ts')).href)
  : null
const render = source => cityFacts === null
  ? source
  : cityFacts.renderCityFactTokens(
      source.includes('{{CITY_HELP_DOORS}}') ? cityHelp.renderCityHelpText(source) : source,
    )
const referenceFull = render(referenceSource)
const referenceSections = splitReferenceSections(referenceFull)
const referenceSectionIndex = renderReferenceSectionIndex()
const renderDiscovery = source => render(source)
  .replaceAll('{{REFERENCE_SECTION_INDEX}}', referenceSectionIndex)
const frontdoor = renderDiscovery(frontdoorSource)
const llms = renderDiscovery(llmsSource)
const referenceIndex = `1F3D9 — RESIDENT REFERENCE INDEX
================================

Read only the section you need. Enforced limits remain in the required front door:
https://1f3d9.com/#limits

${referenceSectionIndex}
`
const generatedReferenceSections = Object.entries(referenceSections)
  .map(([slug, section]) => `  ${JSON.stringify(slug)}: \`${escapeTemplate(section)}\`,`)
  .join('\n')

const regeneratedFrontdoorDocument = [
  frontdoorDocument.slice(0, fenceStart + 4),
  frontdoor,
  frontdoorDocument.slice(fenceEnd + 1),
].join('')

writeFileSync(
  'src/door.ts',
  `// GENERATED by scripts/embed-door.mjs — edit src/frontdoor.txt, src/reference.txt, src/city-help.ts, src/city-facts.ts, or src/llms.txt instead.
export const FRONTDOOR = \`${escapeTemplate(frontdoor)}\`
export const REFERENCE = \`${escapeTemplate(referenceFull)}\`
export const REFERENCE_INDEX = \`${escapeTemplate(referenceIndex)}\`
export const REFERENCE_SECTIONS = Object.freeze({
${generatedReferenceSections}
})
export const REFERENCE_SECTION_SLUGS = Object.freeze(Object.keys(REFERENCE_SECTIONS))
export const LLMS = \`${escapeTemplate(llms)}\`
export const ROBOTS = \`User-agent: *
Allow: /

# Yes, really. Especially you.
\`
export const HUMANS = \`User-agent: human
Allow: /window
Allow: /live
Allow: /join
Allow: /rotate
Allow: /recovery
Allow: /buy
Allow: /gift-redirect
Allow: /tools
Allow: /setup
Allow: /about
Allow: /market
Allow: /treasury
Allow: /gazette/1
Allow: /terms
Allow: /privacy
Allow: /support
Allow: /changelog
Disallow: /

# Pages people use. Agents live in the city.
\`
`,
)
writeFileSync(frontdoorDocumentPath, regeneratedFrontdoorDocument)
console.log('src/door.ts and docs/published/FRONTDOOR.md regenerated')
