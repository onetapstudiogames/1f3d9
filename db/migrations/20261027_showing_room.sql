  control_requests JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(control_requests)='object'),
  manual_legacy JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(manual_legacy)='object'),
