CREATE OR REPLACE FUNCTION protect_showing_room_contest() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'showing room questions are retained; cancel a queued question instead'
      USING ERRCODE='23514',CONSTRAINT='showing_room_contest_retained';
  END IF;
  IF NEW.id<>OLD.id OR NEW.request_id<>OLD.request_id OR NEW.request_hash<>OLD.request_hash
    OR NEW.created_at<>OLD.created_at THEN
    RAISE EXCEPTION 'the original showing room question identity cannot change'
      USING ERRCODE='23514',CONSTRAINT='showing_room_contest_identity';
  END IF;
  IF OLD.state<>'queued' AND (to_jsonb(NEW)-'state') IS DISTINCT FROM (to_jsonb(OLD)-'state') THEN
    RAISE EXCEPTION 'an opened showing room question is immutable; queue a new question instead'
      USING ERRCODE='23514',CONSTRAINT='showing_room_contest_published';
  END IF;
  IF NOT (NEW.state=OLD.state OR (OLD.state='queued' AND NEW.state IN ('open','cancelled'))
    OR (OLD.state='open' AND NEW.state='completed')) THEN
    RAISE EXCEPTION 'this showing room question cannot return to an earlier state'
      USING ERRCODE='23514',CONSTRAINT='showing_room_contest_state';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS showing_room_contest_protected ON showing_room_contests;
CREATE TRIGGER showing_room_contest_protected BEFORE UPDATE OR DELETE ON showing_room_contests
FOR EACH ROW EXECUTE FUNCTION protect_showing_room_contest();

CREATE OR REPLACE FUNCTION protect_showing_room_run() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' OR OLD.completed_at IS NOT NULL THEN
    RAISE EXCEPTION 'completed showing room counts are immutable and retained; add a separate correction instead'
      USING ERRCODE='23514',CONSTRAINT='showing_room_run_completed';
  END IF;
  IF NEW.id<>OLD.id OR NEW.slot_at<>OLD.slot_at OR NEW.contest_id IS DISTINCT FROM OLD.contest_id
    OR NEW.contest_slot_at IS DISTINCT FROM OLD.contest_slot_at
    OR NEW.recovery_run_id IS DISTINCT FROM OLD.recovery_run_id THEN
    RAISE EXCEPTION 'a showing room run must keep its original contest and Monday slot'
      USING ERRCODE='23514',CONSTRAINT='showing_room_run_identity';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS showing_room_run_protected ON showing_room_runs;
CREATE TRIGGER showing_room_run_protected BEFORE UPDATE OR DELETE ON showing_room_runs
FOR EACH ROW EXECUTE FUNCTION protect_showing_room_run();

CREATE OR REPLACE FUNCTION require_showing_room_run_complete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS(SELECT 1 FROM showing_room_runs WHERE id=NEW.id AND completed_at IS NULL) THEN
    RAISE EXCEPTION 'the showing room count did not finish; retry the same Monday slot'
      USING ERRCODE='23514',CONSTRAINT='showing_room_run_complete';
  END IF;
  RETURN NULL;
END $$;
DROP TRIGGER IF EXISTS showing_room_run_complete ON showing_room_runs;
CREATE CONSTRAINT TRIGGER showing_room_run_complete AFTER INSERT OR UPDATE ON showing_room_runs
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION require_showing_room_run_complete();

CREATE OR REPLACE FUNCTION protect_showing_room_publication() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP<>'INSERT' THEN
    RAISE EXCEPTION 'showing room publication links are immutable; keep the original note'
      USING ERRCODE='23514',CONSTRAINT='showing_room_publication_retained';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM showing_room_control WHERE id=1 AND enabled AND activated_at IS NOT NULL) THEN
    RAISE EXCEPTION 'showing room service publications are not active; complete the verified activation first'
      USING ERRCODE='23514',CONSTRAINT='showing_room_publication_inactive';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM showing_room_runs WHERE id=NEW.run_id AND completed_at IS NULL) THEN
    RAISE EXCEPTION 'a publication needs the unfinished showing room run that will post it'
      USING ERRCODE='23514',CONSTRAINT='showing_room_publication_run';
  END IF;
  IF EXISTS(SELECT 1 FROM notes WHERE id=NEW.note_id) THEN
    RAISE EXCEPTION 'a showing room publication link must be reserved before its note is posted'
      USING ERRCODE='23514',CONSTRAINT='showing_room_publication_reserved';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS showing_room_publication_protected ON showing_room_publications;
CREATE TRIGGER showing_room_publication_protected BEFORE INSERT OR UPDATE OR DELETE ON showing_room_publications
FOR EACH ROW EXECUTE FUNCTION protect_showing_room_publication();

CREATE OR REPLACE FUNCTION validate_showing_room_note() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE publication showing_room_publications;
BEGIN
  SELECT * INTO publication FROM showing_room_publications WHERE note_id=NEW.id;
  IF FOUND AND (NEW.author_id<>1 OR NEW.place_id<>publication.place_id OR NEW.walk_to_read
    OR char_length(NEW.body)>4000) THEN
    RAISE EXCEPTION 'a showing room service note must be a public founder note in its recorded room within 4000 characters'
      USING ERRCODE='23514',CONSTRAINT='showing_room_publication_note';
  END IF;
  IF NEW.place_id=438 THEN
    PERFORM pg_advisory_xact_lock(524128266,438);
    IF EXISTS(SELECT 1 FROM showing_room_control WHERE id=1 AND enabled) THEN
      NEW.created_at:=clock_timestamp();
    END IF;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS showing_room_note_admission ON notes;
CREATE TRIGGER showing_room_note_admission BEFORE INSERT ON notes
FOR EACH ROW EXECUTE FUNCTION validate_showing_room_note();

CREATE OR REPLACE FUNCTION retain_showing_room_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'showing room history must be retained; pause future runs instead'
    USING ERRCODE='23514',CONSTRAINT='showing_room_history_retained';
END $$;
DO $showing_room_retention$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['showing_room_contests','showing_room_runs','showing_room_publications','showing_room_control'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I',table_name||'_no_truncate',table_name);
    EXECUTE format('CREATE TRIGGER %I BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION retain_showing_room_history()',table_name||'_no_truncate',table_name);
  END LOOP;
END $showing_room_retention$;

