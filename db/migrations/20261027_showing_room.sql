CREATE TABLE IF NOT EXISTS showing_room_contests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id TEXT NOT NULL UNIQUE CHECK (length(request_id) BETWEEN 1 AND 128),
  request_hash TEXT NOT NULL,
  title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
  prompt TEXT NOT NULL CHECK (char_length(prompt) BETWEEN 1 AND 1800),
  state TEXT NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','open','completed','cancelled','manual-legacy')),
  revision INTEGER NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  rule_version TEXT NOT NULL DEFAULT 'showing-room-v1',
  question_number INTEGER CHECK (question_number > 0),
  rules_note_id INTEGER REFERENCES notes(id),
  opened_at TIMESTAMPTZ,
  entry_closes_at TIMESTAMPTZ,
  vote_closes_at TIMESTAMPTZ,
  CONSTRAINT showing_room_contest_rule CHECK (state='manual-legacy' OR rule_version='showing-room-v1'),
  CONSTRAINT showing_room_contest_dates CHECK (
    (state IN ('queued','cancelled') AND question_number IS NULL AND rules_note_id IS NULL
      AND opened_at IS NULL AND entry_closes_at IS NULL AND vote_closes_at IS NULL)
    OR (state IN ('open','completed','manual-legacy') AND question_number IS NOT NULL
      AND rules_note_id IS NOT NULL AND opened_at IS NOT NULL AND entry_closes_at > opened_at
      AND vote_closes_at > entry_closes_at)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS showing_room_one_open ON showing_room_contests ((state)) WHERE state='open';
CREATE UNIQUE INDEX IF NOT EXISTS showing_room_question_number ON showing_room_contests (question_number) WHERE question_number IS NOT NULL;
CREATE INDEX IF NOT EXISTS showing_room_queue_order ON showing_room_contests (created_at,id) WHERE state='queued';

CREATE TABLE IF NOT EXISTS showing_room_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_at TIMESTAMPTZ NOT NULL UNIQUE,
  contest_id BIGINT UNIQUE REFERENCES showing_room_contests(id),
  contest_slot_at TIMESTAMPTZ,
  recovery_run_id BIGINT REFERENCES showing_room_runs(id),
  result JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(result)='object'),
  next_contest_id BIGINT REFERENCES showing_room_contests(id),
  completed_at TIMESTAMPTZ,
  late BOOLEAN NOT NULL DEFAULT FALSE,
  skipped BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT showing_room_run_monday CHECK (extract(isodow FROM slot_at AT TIME ZONE 'UTC')=1
    AND (slot_at AT TIME ZONE 'UTC')::time=time '15:00:00'),
  CONSTRAINT showing_room_run_recovery CHECK (recovery_run_id IS NULL OR (contest_id IS NULL AND recovery_run_id<>id))
);

CREATE TABLE IF NOT EXISTS showing_room_publications (
  run_id BIGINT NOT NULL REFERENCES showing_room_runs(id),
  purpose TEXT NOT NULL CHECK (purpose IN ('count','winners','next_rules','gazette','square')),
  part INTEGER NOT NULL CHECK (part > 0 AND (purpose IN ('count','winners') OR part=1)),
  note_id INTEGER NOT NULL UNIQUE REFERENCES notes(id) DEFERRABLE INITIALLY DEFERRED,
  place_id INTEGER NOT NULL REFERENCES places(id),
  PRIMARY KEY (run_id,purpose,part),
  CONSTRAINT showing_room_publication_room CHECK (
    (purpose IN ('count','winners','next_rules') AND place_id=438)
    OR (purpose='gazette' AND place_id=454) OR (purpose='square' AND place_id=3)
  )
);

CREATE TABLE IF NOT EXISTS showing_room_control (
  id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id=1),
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  paused BOOLEAN NOT NULL DEFAULT TRUE,
  first_slot_at TIMESTAMPTZ,
  first_question_number INTEGER CHECK (first_question_number > 0),
  square_announcement BOOLEAN NOT NULL DEFAULT FALSE,
