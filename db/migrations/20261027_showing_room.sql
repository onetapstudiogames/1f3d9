CREATE OR REPLACE FUNCTION enforce_gazette_submission_limit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  cycle_start TIMESTAMPTZ;
  submissions INTEGER;
  withdrawal_target INTEGER;
BEGIN
  IF NEW.place_id <> 454 THEN
    RETURN NEW;
  END IF;

  -- Note actions take the resident retry lock first. The printer takes only the
  -- second lock, so lock order cannot cycle.
  PERFORM pg_advisory_xact_lock(524128260, NEW.author_id);
  PERFORM pg_advisory_xact_lock(524128261, 454);

  IF NOT gazette_submission_room_is_open() THEN
    RAISE EXCEPTION 'Gazette submission room #454 is not open; read GET /api/gazette and submit only when submission_room.submissions_open is true'
      USING ERRCODE = '23514', CONSTRAINT = 'gazette_submission_room_closed';
  END IF;

  -- The database clock owns the public submission time. A direct writer cannot
  -- escape a weekly quota or create a retroactive print candidate by supplying
  -- a past or future created_at value.
  NEW.created_at := clock_timestamp();
  IF gazette_withdrawals_are_open()
    AND gazette_withdrawal_command_reserved(NEW.body)
  THEN
    withdrawal_target := gazette_withdrawal_target(NEW.body);
    IF withdrawal_target IS NULL THEN
      RAISE EXCEPTION 'Gazette withdrawal must be exactly WITHDRAW #<your-note-id>'
        USING ERRCODE = '23514', CONSTRAINT = 'gazette_withdrawal_command_invalid';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.author_id=1 AND EXISTS(SELECT 1 FROM showing_room_control WHERE id=1 AND enabled AND activated_at IS NOT NULL)
    AND EXISTS(SELECT 1 FROM showing_room_publications p
    JOIN showing_room_runs r ON r.id=p.run_id
    WHERE p.note_id=NEW.id AND p.purpose='gazette' AND p.part=1 AND p.place_id=454
      AND r.completed_at IS NULL) THEN RETURN NEW; END IF;

  cycle_start := gazette_cycle_start(NEW.created_at);

  SELECT count(*)::integer
  INTO submissions
  FROM notes existing
  WHERE existing.place_id = 454
    AND existing.author_id = NEW.author_id
    AND existing.created_at >= cycle_start
    AND existing.created_at < cycle_start + interval '7 days'
    AND NOT EXISTS (SELECT 1 FROM showing_room_publications p
      WHERE p.note_id=existing.id AND p.purpose='gazette' AND p.place_id=454)
    AND NOT EXISTS (
      SELECT 1 FROM gazette_withdrawals withdrawal
      WHERE withdrawal.command_note_id = existing.id
    );

  IF submissions >= 3 THEN
    RAISE EXCEPTION '3 Gazette submissions per resident are allowed from Monday 16:00 UTC inclusive to the next Monday 16:00 UTC exclusive; this Gazette week''s 3 submissions are used; retry at %',
      to_char(
        (cycle_start + interval '7 days') AT TIME ZONE 'UTC',
        'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'
      )
      USING ERRCODE = '23514', CONSTRAINT = 'gazette_submission_weekly_limit';
  END IF;
  RETURN NEW;
END
$$;

CREATE OR REPLACE FUNCTION protect_gazette_submission_room()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.id = 454 THEN
      RAISE EXCEPTION 'Gazette room #454 is a protected city service; it cannot be deleted, traded, transferred, or repurposed'
        USING ERRCODE = '23514', CONSTRAINT = 'gazette_submission_room_lifecycle';
    END IF;
    RETURN OLD;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.id = 454 AND gazette_submission_room_state(NEW) <> 'closed' THEN
      RAISE EXCEPTION 'Gazette room #454 must begin as the exact closed submission shell described by the city contract'
        USING ERRCODE = '23514', CONSTRAINT = 'gazette_submission_room_lifecycle';
    END IF;
    RETURN NEW;
  END IF;

  IF OLD.id <> 454 AND NEW.id <> 454 THEN
    RETURN NEW;
  END IF;
  IF OLD.id IS DISTINCT FROM NEW.id THEN
    RAISE EXCEPTION 'Gazette room #454 is a protected city service; its identity cannot change'
      USING ERRCODE = '23514', CONSTRAINT = 'gazette_submission_room_lifecycle';
  END IF;
  IF NEW IS NOT DISTINCT FROM OLD THEN
    RETURN NEW;
  END IF;

  -- The system-owned activity summary preserves the exact protected room state.
  IF to_jsonb(NEW) ? 'last_public_action_at'
    AND to_jsonb(OLD) ? 'last_public_action_at'
    AND to_jsonb(NEW)->'last_public_action_at' IS DISTINCT FROM to_jsonb(OLD)->'last_public_action_at'
    AND to_jsonb(NEW) - 'last_public_action_at' = to_jsonb(OLD) - 'last_public_action_at'
    AND gazette_submission_room_state(NEW) IN ('closed', 'open', 'withdrawals_open')
    AND gazette_submission_room_state(NEW) = gazette_submission_room_state(OLD)
    AND gazette_submission_room_has_no_forbidden_contents()
    AND gazette_submission_room_guards_ready() THEN
    RETURN NEW;
  END IF;

  IF gazette_submission_room_state(OLD) = 'closed'
    AND gazette_submission_room_state(NEW) = 'open'
    AND to_regclass('public.gazette_issues') IS NOT NULL
    AND to_regclass('public.gazette_issue_entries') IS NOT NULL
    AND to_regclass('city_snapshot.public_records_v2') IS NOT NULL
    AND gazette_submission_room_has_no_forbidden_contents()
    AND gazette_submission_room_guards_ready()
    AND NOT EXISTS (SELECT 1 FROM notes WHERE place_id = 454)
    AND (
      SELECT count(*)
      FROM events event
      WHERE event.kind = 'place_edited'
        AND event.actor = 'the city'
        AND event.detail = '{"place_id":454,"gazette_submission_room_opened":true}'::jsonb
    ) = 1
  THEN
    RETURN NEW;
  END IF;

  IF gazette_submission_room_state(OLD) = 'open'
    AND gazette_submission_room_state(NEW) = 'withdrawals_open'
    AND gazette_submission_room_has_no_forbidden_contents()
    AND gazette_submission_room_guards_ready()
    AND (
      SELECT count(*)
      FROM events event
      WHERE event.kind = 'place_edited'
        AND event.actor = 'the city'
        AND event.detail = '{"place_id":454,"gazette_submission_room_opened":true}'::jsonb
    ) = 1
    AND (
      SELECT count(*)
      FROM events event
      WHERE event.kind = 'place_edited'
        AND event.actor = 'the city'
        AND event.detail = '{"place_id":454,"gazette_withdrawals_opened":true}'::jsonb
    ) = 1
  THEN
    RETURN NEW;
  END IF;

  IF gazette_submission_room_state(OLD)='withdrawals_open'
    AND gazette_submission_room_state(NEW)='withdrawals_open'
    AND NEW.description='Leave a note here for The Gazette. Every Monday at 16:00 UTC, the automatic printer permanently assigns every unprinted submission made before the cutoff to the next issue, oldest first with its author, note ID, and time. An author may withdraw their own submission strictly before that same print tick by leaving exactly WITHDRAW #<their-note-id>; the issue keeps that entry''s place as a one-line withdrawal notice. Only while withdrawals are open, a note whose opening is exact uppercase WITHDRAW, optional whitespace, then # is read as a withdrawal command; every other opening or shape is an ordinary submission. A reserved opening that is not exactly WITHDRAW #<their-note-id> is refused instead of printing. The founder and other residents have no override. Printing and withdrawal never delete, edit, move, or copy the source note. The one recorded weekly showing room report from founder #1 uses no daily or weekly note slot; all other notes keep their ordinary limits.' AND NEW.purpose='Three ordinary submissions per resident per Gazette week; ordinary notes use daily quota. The recorded showing room report uses neither quota. WITHDRAW plus optional whitespace then # is reserved; commands never print or restore the target slot.'
    AND OLD.description='Leave a note here for The Gazette. Every Monday at 16:00 UTC, the automatic printer permanently assigns every unprinted submission made before the cutoff to the next issue, oldest first with its author, note ID, and time. An author may withdraw their own submission strictly before that same print tick by leaving exactly WITHDRAW #<their-note-id>; the issue keeps that entry''s place as a one-line withdrawal notice. Only while withdrawals are open, a note whose opening is exact uppercase WITHDRAW, optional whitespace, then # is read as a withdrawal command; every other opening or shape is an ordinary submission. A reserved opening that is not exactly WITHDRAW #<their-note-id> is refused instead of printing. The founder and other residents have no override. Printing and withdrawal never delete, edit, move, or copy the source note.' AND OLD.purpose='Three submissions per resident per Gazette week; all notes use the daily quota. Closed: every body is a submission. Open: uppercase WITHDRAW plus optional whitespace then # is reserved; commands use no weekly slot, never print, and do not restore the target slot.'
    AND (to_jsonb(NEW)-'description'-'purpose')=(to_jsonb(OLD)-'description'-'purpose')
    AND EXISTS(SELECT 1 FROM showing_room_control WHERE id=1 AND activated_at IS NOT NULL)
    AND showing_room_guards_ready()
  THEN RETURN NEW; END IF;

  RAISE EXCEPTION 'Gazette room #454 is a protected city service; it must remain one exact contract state and change only through guarded activation'
    USING ERRCODE = '23514', CONSTRAINT = 'gazette_submission_room_lifecycle';
END
$$;

CREATE OR REPLACE FUNCTION activate_showing_room_service(verified_commit TEXT)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE control showing_room_control;
BEGIN
  IF verified_commit IS NULL OR verified_commit !~ '^[a-f0-9]{40}$' THEN
    RAISE EXCEPTION 'showing room activation needs the verified deployed commit; run the named activation ceremony'
      USING ERRCODE='23514',CONSTRAINT='showing_room_activation_commit';
  END IF;
  PERFORM pg_advisory_xact_lock(524128265,438);
  PERFORM 1 FROM residents WHERE id=1 FOR NO KEY UPDATE;
  PERFORM pg_advisory_xact_lock(524128260,1);
  PERFORM pg_advisory_xact_lock(524128266,438);
  PERFORM place.id FROM places place JOIN (
    WITH RECURSIVE tree AS (
      SELECT id AS origin,id,parent_id,0 AS depth FROM places WHERE id IN (438,454)
      UNION ALL
      SELECT tree.origin,parent.id,parent.parent_id,tree.depth+1
      FROM tree JOIN places parent ON parent.id=tree.parent_id
    ) SELECT origin,max(depth) AS depth FROM tree GROUP BY origin
  ) planned ON planned.origin=place.id
  ORDER BY planned.depth,place.id FOR NO KEY UPDATE OF place;
  PERFORM pg_advisory_xact_lock(524128261,454);
  SELECT * INTO control FROM showing_room_control WHERE id=1 FOR UPDATE;
  IF NOT FOUND OR NOT showing_room_guards_ready() THEN
    RAISE EXCEPTION 'showing room stores and guards must be installed before activation'
      USING ERRCODE='23514',CONSTRAINT='showing_room_activation_guards';
  END IF;
  PERFORM 1 FROM places p WHERE p.id=438 AND p.owner_id=1 AND p.retired_at IS NULL
    AND NOT p.quiet AND p.open_to_notes
    AND NOT EXISTS(SELECT 1 FROM LATERAL (
      SELECT action FROM moderation_actions WHERE target_type='place' AND target_id=p.id
      ORDER BY created_at DESC,id DESC LIMIT 1
    ) m WHERE m.action='remove');
  IF NOT FOUND THEN
    RAISE EXCEPTION 'the showing room must be an active public room owned by founder #1 and open to notes before activation'
      USING ERRCODE='23514',CONSTRAINT='showing_room_activation_room';
  END IF;
  IF control.activated_at IS NOT NULL THEN
    IF control.activation_commit=verified_commit AND gazette_submission_room_is_open()
      AND EXISTS(SELECT 1 FROM places WHERE id=454 AND description='Leave a note here for The Gazette. Every Monday at 16:00 UTC, the automatic printer permanently assigns every unprinted submission made before the cutoff to the next issue, oldest first with its author, note ID, and time. An author may withdraw their own submission strictly before that same print tick by leaving exactly WITHDRAW #<their-note-id>; the issue keeps that entry''s place as a one-line withdrawal notice. Only while withdrawals are open, a note whose opening is exact uppercase WITHDRAW, optional whitespace, then # is read as a withdrawal command; every other opening or shape is an ordinary submission. A reserved opening that is not exactly WITHDRAW #<their-note-id> is refused instead of printing. The founder and other residents have no override. Printing and withdrawal never delete, edit, move, or copy the source note. The one recorded weekly showing room report from founder #1 uses no daily or weekly note slot; all other notes keep their ordinary limits.' AND purpose='Three ordinary submissions per resident per Gazette week; ordinary notes use daily quota. The recorded showing room report uses neither quota. WITHDRAW plus optional whitespace then # is reserved; commands never print or restore the target slot.') THEN RETURN; END IF;
    RAISE EXCEPTION 'showing room activation already names another deployment or room state; ask the founder to review it'
      USING ERRCODE='23514',CONSTRAINT='showing_room_activation_replay';
  END IF;
  PERFORM 1 FROM places WHERE id=454 AND description='Leave a note here for The Gazette. Every Monday at 16:00 UTC, the automatic printer permanently assigns every unprinted submission made before the cutoff to the next issue, oldest first with its author, note ID, and time. An author may withdraw their own submission strictly before that same print tick by leaving exactly WITHDRAW #<their-note-id>; the issue keeps that entry''s place as a one-line withdrawal notice. Only while withdrawals are open, a note whose opening is exact uppercase WITHDRAW, optional whitespace, then # is read as a withdrawal command; every other opening or shape is an ordinary submission. A reserved opening that is not exactly WITHDRAW #<their-note-id> is refused instead of printing. The founder and other residents have no override. Printing and withdrawal never delete, edit, move, or copy the source note.' AND purpose='Three submissions per resident per Gazette week; all notes use the daily quota. Closed: every body is a submission. Open: uppercase WITHDRAW plus optional whitespace then # is reserved; commands use no weekly slot, never print, and do not restore the target slot.';
  IF NOT FOUND OR NOT gazette_withdrawals_are_open() OR NOT gazette_submission_room_has_no_forbidden_contents() THEN
    RAISE EXCEPTION 'the Gazette room must match its current open submission and withdrawal contract before activation'
      USING ERRCODE='23514',CONSTRAINT='showing_room_activation_gazette';
  END IF;
  UPDATE showing_room_control SET activation_commit=verified_commit,activated_at=clock_timestamp() WHERE id=1;
  UPDATE places SET description='Leave a note here for The Gazette. Every Monday at 16:00 UTC, the automatic printer permanently assigns every unprinted submission made before the cutoff to the next issue, oldest first with its author, note ID, and time. An author may withdraw their own submission strictly before that same print tick by leaving exactly WITHDRAW #<their-note-id>; the issue keeps that entry''s place as a one-line withdrawal notice. Only while withdrawals are open, a note whose opening is exact uppercase WITHDRAW, optional whitespace, then # is read as a withdrawal command; every other opening or shape is an ordinary submission. A reserved opening that is not exactly WITHDRAW #<their-note-id> is refused instead of printing. The founder and other residents have no override. Printing and withdrawal never delete, edit, move, or copy the source note. The one recorded weekly showing room report from founder #1 uses no daily or weekly note slot; all other notes keep their ordinary limits.',purpose='Three ordinary submissions per resident per Gazette week; ordinary notes use daily quota. The recorded showing room report uses neither quota. WITHDRAW plus optional whitespace then # is reserved; commands never print or restore the target slot.' WHERE id=454;
  INSERT INTO events(kind,actor,detail) VALUES('place_edited','the city',jsonb_build_object('place_id',454));
  IF NOT gazette_withdrawals_are_open() THEN
    RAISE EXCEPTION 'the Gazette room did not retain its submission and withdrawal contract; activation was rolled back'
      USING ERRCODE='23514',CONSTRAINT='showing_room_activation_postcondition';
  END IF;
END $$;
REVOKE ALL ON FUNCTION activate_showing_room_service(TEXT) FROM PUBLIC,city_snapshot_export;

DO $showing_room_postconditions$
BEGIN
  IF NOT showing_room_guards_ready() OR (SELECT count(*) FROM showing_room_control)<>1 THEN
    RAISE EXCEPTION 'showing room installation did not match its reviewed stores, limits and guards; leave the service paused and review the migration'
      USING ERRCODE='23514',CONSTRAINT='showing_room_installation_postconditions';
  END IF;
  IF EXISTS(SELECT 1 FROM showing_room_control WHERE activated_at IS NULL AND (enabled OR NOT paused)) THEN
    RAISE EXCEPTION 'an unactivated showing room installation must remain off and paused'
      USING ERRCODE='23514',CONSTRAINT='showing_room_installation_dormant';
  END IF;
END $showing_room_postconditions$;
